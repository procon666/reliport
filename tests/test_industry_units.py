# -*- coding: utf-8 -*-
"""重工业量纲专项回归（钢铁/原油/煤炭/电力/化工 —— 真实检索修复固化）。

背景（真联网检索重工业素材，见 real_industry_blind.py）：既有量纲缺大宗工业单位与
产量/消费量名词指标。修复：
1. _NUM_RE/_COUNT_UNIT_RE 补 千克/公斤/千瓦时/千瓦/桶：'601.1千克'、'98521亿千瓦时'、
   '33.49亿千瓦' 等不再截断/漏抽；
2. _CLAIM_KEYWORDS 补"消费量"名词指标（'人均钢材表观消费量601.1千克'）；
3. '同比增加/同比提高'收录（与'同比增长'同义）→ 19% 归增长率而非被后文'约占'误伤；
4. '约占'收录归'占比' → '…同比增加19%，约占全部发电量的35%' 中 19%增长/35%占比分家。
"""
import sys
sys.path.insert(0, '.')
from research_agent.analyzer import _sentence_claims

PASS = 0
FAIL = 0

def check(name, cond, detail=""):
    global PASS, FAIL
    tag = "PASS" if cond else "FAIL"
    if cond:
        PASS += 1
    else:
        FAIL += 1
    print(f"[{tag}] {name}" + (f"  {detail}" if detail else ""))

def rows(sent):
    return [(c["value"], c["indicator"]) for c in _sentence_claims(sent, "x")]

# ---- 1. 千克单位 + 消费量指标 ----
g = rows("2024年中国人均钢材表观消费量降至601.1千克，排名全球第三。")
check("千克:601.1千克→消费量", ("601.1千克", "消费量") in g, f"got={g}")

# ---- 2. 千瓦时/千瓦完整单位 ----
g = rows("2024年，全社会用电量98521亿千瓦时，同比增长6.8%。")
check("千瓦时:98521亿千瓦时完整", ("98521亿千瓦时", "规模") in g, f"got={g}")
g = rows("2024年，全国累计发电装机容量达33.49亿千瓦，新增发电装机容量4.29亿千瓦。")
check("千瓦:33.49/4.29亿千瓦并存(装机容量独立后归装机容量)",
      ("33.49亿千瓦", "装机容量") in g and ("4.29亿千瓦", "装机容量") in g, f"got={g}")

# ---- P2-1 装机词族分桶：存量(装机容量) vs 增量(装机量) ----
g = rows("截至2026年7月底，全国光伏发电装机容量达到12.86亿千瓦，在全国40.8亿千瓦的发电总装机中占比达31.5%。")
check("装机容量独立:12.86/40.8(总装机)→装机容量",
      ("12.86亿千瓦", "装机容量") in g and ("40.8亿千瓦", "装机容量") in g, f"got={g}")
g = rows("2026年1-5月全国太阳能发电新增装机59.59GW，其中5月单月仅8.68GW。")
check("新增装机→装机量(与存量装机容量分桶)",
      ("59.59GW", "装机量") in g and ("8.68GW", "装机量") in g, f"got={g}")
g = rows("2026年6月光伏新增装机规模12.48GW，较去年同期的14.36GW，同比下降13.09%。")
check("'装机规模'复合不被'规模'抢注(归装机量)",
      ("12.48GW", "装机量") in g and ("14.36GW", "装机量") in g, f"got={g}")

# ---- P2-B 产销并列展开：前值产量、后值销量 ----
g = rows("汽车产销分别完成257.3万辆和258.4万辆，环比分别下降6.8％和8％。")
check("产销展开:257.3→产量/258.4→销量",
      ("257.3万辆", "产量") in g and ("258.4万辆", "销量") in g, f"got={g}")
g = rows("2025年，中国汽车产销分别完成3453.1万辆和3440万辆，同比分别增长10.4%和9.4%。")
check("产销展开(万辆):3453.1→产量/3440→销量",
      ("3453.1万辆", "产量") in g and ("3440万辆", "销量") in g, f"got={g}")

# ---- 3. 同比增加/同比提高 → 增长率 ----
g = rows("2024年，全国可再生能源发电量达3.46万亿千瓦时，同比增加19%，约占全部发电量的35%。")
check("同比增加19%→增长率(非占比)",
      ("3.46万亿千瓦时", "规模") in g and ("19%", "增长率") in g, f"got={g}")
check("约占35%→占比(与19%分家)", ("35%", "占比") in g, f"got={g}")
g = rows("2024年12月，中国粗钢产量为7597万吨，同比提高11.8%。")
check("同比提高11.8%→增长率", ("7597万吨", "规模") in g and ("11.8%", "增长率") in g, f"got={g}")

# ---- 4. 回归护栏：既有句式不受新单位影响 ----
g = rows("2024年中国游戏产业市场规模已突破3257.8亿元，同比增长7.53%。")
check("行业规模/增长率不受影响", ("3257.8亿元", "规模") in g and ("7.53%", "增长率") in g, f"got={g}")
g = rows("该产品质保期3年销量10万台。")
check("质保期时间跨度仍过滤", ("10万台", "销量") in g and "3" not in [v for v, _ in g], f"got={g}")

# ---- P2-3a OLED出货面积(平方米)独立指标 ----
g = rows("展望2026年，中国市场OLED面板出货面积预计达720万平方米，同比增长26.2%。")
check("OLED出货面积:720万平方米→出货面积(非出货量)",
      ("720万平方米", "出货面积") in g, f"got={g}")

# ---- P2-3b 稼动率（%比率指标）----
g = rows("2026年2月行业稼动率降至80%左右，3月已有所回升。")
check("稼动率:80%→稼动率(非增长率)", ("80%", "稼动率") in g, f"got={g}")

# ---- P2-3c 投资指标 + 世代号剔除 ----
g = rows("京东方在成都投建的第8.6代AMOLED生产线总投资630亿元。")
check("投资:630亿元→投资", ("630亿元", "投资") in g, f"got={g}")
check("世代号:第8.6代不抽8.6", "8.6" not in [v for v, _ in g], f"got={g}")

print(f"\n========== 重工业量纲专项回归：{PASS} 通过 / {FAIL} 失败 ==========")
sys.exit(1 if FAIL else 0)
