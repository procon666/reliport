# ---- 召回(值命中) ----
tot = hit = 0
over_miss = []
for sent, expects in REAL:
    got = _sentence_claims(sent, "u")
    got_vals = [c["value"] for c in got]
    for (_i, exp_v, _y) in expects:
        tot += 1
        if any(num_eq(v, exp_v) for v in got_vals):
            hit += 1
        else:
            over_miss.append((sent[:30], exp_v))
print(f"■ 召回(盲测61值): {hit}/{tot} = {hit/tot*100:.0f}%")
if over_miss:
    for s, v in over_miss:
        print(f"    MISS {v:<10} in {s}")

# ---- 膨胀(探针句,产出主张数 vs 合理期望) ----
print("\n■ 精确率/膨胀探针:")
tot_probe = extra = 0
for sent, expect_cnt in PROBE:
    got = _sentence_claims(sent, "u")
    n = len(got)
    tot_probe += 1
    over = n - expect_cnt
    if over > 0:
        extra += over
        print(f"    期望≈{expect_cnt} 实际={n} (+{over}) | {sent[:26]}")
print(f"    探针句数={tot_probe}  累计多抽条数={extra}")
