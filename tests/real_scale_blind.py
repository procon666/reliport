def num_eq(a, b):
    na = _value_to_number(a); nb = _value_to_number(b)
    if na and nb:
        if na[1] != nb[1]:
            return False
        return _values_close(a, b)
    return a.replace(" ", "") == b.replace(" ", "")

def value_recalled(got, exp_v):
    return any(num_eq(c["value"], exp_v) for c in got)

