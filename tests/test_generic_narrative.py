"""手游史·通用性冷启动回归测试。

背景：验证引擎不只适用"行业报告"，能普适处理手游发展史这类跨主题、跨时间、
跨量纲的"史/作品叙事"素材。以下手游史典型句**不预收手游专用词表**，仅靠
结构式切分 + 量纲对称别名 + 游戏域量纲尾清洗即可正确抽取。

覆盖（对照本轮通用性修复）：
  1. 下载短式"下载→下载量"别名（无量"下载"不落规模）
  2. 句首期词"首月/全年"不残留主体；跨分句承前主体可还原
  3. "其中/其余"承前连接词不进主体
  4. "覆盖200多个国家"的范围数不误抽成量值
  5. 年锚碰撞修复：首年营收不把主体截成"《X》首"
  6. 股价类资产价格主体锚：任天堂股价→任天堂
  7. 游戏域量纲尾清洗：仅游戏句触发，通用句不动
  8. 书名号归一：主体去掉《》（《王者荣耀》与王者荣耀可交叉汇成 high）
注：期望主体为归一化后（不带《》）；输入句保留《》（真实文本形态）。
"""
import sys
sys.path.insert(0, '.')
from research_agent.analyzer import _sentence_claims

PASS = 0
FAIL = 0

def check(name, cond, detail=""):
    global PASS, FAIL
    if cond:
        PASS += 1
    else:
        FAIL += 1
        print(f"[FAIL] {name}  {detail}")

def rows(sent):
    return [(c["value"], c["indicator"], c["subject"]) for c in _sentence_claims(sent, "u")]

# ---- 1. 下载短式别名：无量"下载"归下载量而非规模 ----
g = rows("《愤怒的小鸟》2010年发布后累计下载量突破10亿次。")
check("带'量'下载量→下载量|10亿|愤怒的小鸟(书名号归一)",
      ("10亿", "下载量", "愤怒的小鸟") in g, f"got={g}")

g = rows("《愤怒的小鸟》2010年发布后全球累计下载突破10亿次。")
check("无量'下载'也归下载量(非规模)",
      ("10亿", "下载量", "愤怒的小鸟") in g
      and not any(i == "规模" for _, i, _ in g), f"got={g}")

# ---- 2. 句首期词/跨分句承前主体 ----
g = rows("《王者荣耀》2021年日活跃用户达1亿，全年流水约200亿元。")
check("双值主体都还原王者荣耀(含跨分句'全年流水'兜底)",
      ("1亿", "用户数", "王者荣耀") in g
      and ("200亿元", "流水", "王者荣耀") in g, f"got={g}")

g = rows("米哈游《原神》2020年9月上线，首月全球流水约2.5亿美元。")
check("'首月全球流水'跨分句主体→米哈游原神",
      ("2.5亿美元", "流水", "米哈游原神") in g, f"got={g}")

# ---- 3. 其中承前连接词不进主体 ----
g = rows("中国手游市场2023年实际销售收入约2200亿元，其中出海收入约150亿美元。")
check("'其中出海收入'→主体'出海'(不含其中)",
      ("150亿美元", "收入", "出海") in g, f"got={g}")

# ---- 4. 覆盖地域范围数不误抽成量值 ----
g = rows("截至2024年，《王者荣耀》全球累计下载量超30亿次，玩家覆盖200多个国家。")
check("'覆盖200多个国家'不误抽下载量|200",
      ("30亿", "下载量", "王者荣耀") in g
      and not any(v == "200" for v, _, _ in g), f"got={g}")

# ---- 5. 年锚碰撞修复：首年营收主体不被截成"《X》首" ----
g = rows("《原神》首年营收超10亿美元。")
check("'《原神》首年营收'→主体原神(非截断《原神》首)",
      ("10亿美元", "营收", "原神") in g, f"got={g}")

# ---- 6. 股价资产价格主体锚 ----
g = rows("2016年《Pokemon GO》发布后，任天堂股价一度涨超10%。")
check("'任天堂股价涨超10%'→主体任天堂",
      ("10%", "增长率", "任天堂") in g, f"got={g}")

# ---- 7. 游戏域量纲尾清洗只作用游戏句，通用句不动 ----
# 通用(非游戏)句主体不应因域清洗被改动
g = rows("该公司2023年全球累计营收达200亿元。")
check("通用句(无游戏/书名)主体不受域清洗影响",
      ("200亿元", "营收", "该公司") in g, f"got={g}")

# ---- 8. 书名号归一：主体不带《》 ----
g = rows("《原神》首月全球收入超5亿美元。")
check("游戏句主体不带书名号(归一后)",
      ("5亿美元", "收入", "原神") in g
      and not any("《" in subj or "》" in subj for _, _, subj in g), f"got={g}")

print(f"\n========== 手游史冷启动回归：{PASS} 通过 / {FAIL} 失败 ==========")
sys.exit(1 if FAIL else 0)
