def num_eq(a, b):
    na = _value_to_number(a)
    nb = _value_to_number(b)
    if na and nb:
        if na[1] != nb[1]:
            return False
        return _values_close(a, b)
    return a.replace(" ", "") == b.replace(" ", "")


def subj_ok(exp, got):
    if not exp:
        return True
    g = (got or "").strip()
    if not g:
        return False
    return exp in g or g in exp


def classify(exp_subj, exp_ind, exp_val, got, year_ok):
    """错误分类：值漏 / 指标错 / 主体错。值缺优先，其次指标，再主体。"""
    if not any(num_eq(c["value"], exp_val) for c in got):
        return "value_missing"
    if not any(num_eq(c["value"], exp_val) and c["indicator"] == exp_ind
               for c in got):
        return "indicator_wrong"
    if not any(num_eq(c["value"], exp_val) and c["indicator"] == exp_ind
               and subj_ok(exp_subj, c["subject"]) for c in got):
        return "subject_wrong"
    if not year_ok:
        return "year_wrong"
    return "ok"


