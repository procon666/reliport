TYPE_CN = {"year": "年份错", "subject": "主体错"}


def num_eq(a, b):
    na = _value_to_number(a); nb = _value_to_number(b)
    if na and nb:
        if na[1] != nb[1]:
            return False
        return _values_close(a, b)
    return a.replace(" ", "") == b.replace(" ", "")


def subj_ok(exp, got):
    if not exp:
        return True
    g = (got or "").strip()
    if not g:
        return False
    return exp in g or g in exp


def strict_num_eq(a, b):
    """判定用严格数值相等（KNOWN 期望逐字摘录，不需 _values_close 的微差容忍）。

    用 close 会导致误报：同句存在相近相对值时（军工句 7% 与 7.2%），已修好的
    邻居值会把"仍在错"的目标误判成 REVISIT（2026-07 E2 前置审计时暴露）。"""
    na = _value_to_number(a); nb = _value_to_number(b)
    if na and nb:
        if na[1] != nb[1]:
            return False
        return abs(na[0] - nb[0]) < 1e-9
    return a.replace(" ", "") == b.replace(" ", "")


def still_broken(got, exp):
    es, ei, ev, ey = exp
    return not any(strict_num_eq(c["value"], ev) and c["year"] == ey
                   and c["indicator"] == ei and subj_ok(es, c["subject"])
                   for c in got)


