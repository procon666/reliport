# -*- coding: utf-8 -*-
"""内容平台/服务业量纲专项回归（视频/短视频/流媒体 —— 真联网检索修复固化）。

背景（Tavily 真联网检索视频平台/抖音/Netflix 素材，句子逐字摘录）：
  内容平台的量化事实以 用户/会员/时长/收入/GMV/订阅 为指标，分钟/亿/元 为单位。
  修复：
  1. "用户"裸词收录（→用户数）：'7亿用户/新增507万用户' 不再落笼统"规模"；
  2. "分钟"单位 + "时长"指标：'人均使用时长126分钟' 归 时长|126分钟（原漏抽/错绑用户数）；
  3. "占总"收录（→占比）：'广告收入4200亿，占总收入46.6%' 的 46.6% 不再被远处
     '同比增长'劫持成增长率；
  4. "流水"提为一级指标（游戏/直播收入口径）：'全年流水约200亿' 就近绑流水，
     不被新收录的"用户"抢走；
  5. 代号后缀字母剔除：'5G用户' 的 5（后跟拉丁字母 G）不再被误抽。
"""
import sys
sys.path.insert(0, '.')
from research_agent.analyzer import _sentence_claims

PASS = 0
FAIL = 0

def check(name, cond, detail=""):
    global PASS, FAIL
    tag = "PASS" if cond else "FAIL"
    if cond:
        PASS += 1
    else:
        FAIL += 1
    print(f"[{tag}] {name}" + (f"  {detail}" if detail else ""))

def rows(sent):
    return [(c["value"], c["indicator"]) for c in _sentence_claims(sent, "x")]

# ---- 1. 用户裸词 ----
g = rows("Netflix在2024年第三季度营收达到98.25亿美元，年增长15%，新增507万用户。")
check("507万用户→用户数(非营收)", ("507万", "用户数") in g and ("98.25亿美元", "营收") in g, f"got={g}")
g = rows("2018年1月底，快手以7亿用户、1.2亿的日活量独领风骚。")
check("7亿用户/1.2亿日活→用户数",
      ("7亿", "用户数") in g and ("1.2亿", "用户数") in g, f"got={g}")

# ---- 2. 时长+分钟 ----
g = rows("快手2024年财报显示日活用户4亿，人均使用时长126分钟。")
check("126分钟→时长(单位完整)", ("4亿", "用户数") in g and ("126分钟", "时长") in g, f"got={g}")

# ---- 3. 占总收入 ----
g = rows("抖音2025年预计总收入约9012亿元，同比增长28.3%，广告收入达4200亿元，占总收入46.6%。")
check("占总46.6%→占比(非增长率)",
      ("9012亿元", "收入") in g and ("4200亿元", "收入") in g and ("46.6%", "占比") in g, f"got={g}")

# ---- 4. 流水 ----
g = rows("《王者荣耀》2021年日活跃用户达1亿，全年流水约200亿元。")
check("流水200亿→流水(用户不抢)",
      ("1亿", "用户数") in g and ("200亿元", "流水") in g, f"got={g}")

# ---- 5. 代号后缀字母 ----
g = rows("三大运营商2024年5G用户合计突破10亿户。")
check("5G代号5不抽", "5" not in [v for v, _ in g] and ("10亿", "用户数") in g, f"got={g}")

# ---- 6. 回归护栏 ----
g = rows("2024年中国游戏产业市场规模已突破3257.8亿元，同比增长7.53%。")
check("行业规模/增长率不受影响", ("3257.8亿元", "规模") in g and ("7.53%", "增长率") in g, f"got={g}")

print(f"\n========== 内容平台量纲专项回归：{PASS} 通过 / {FAIL} 失败 ==========")
sys.exit(1 if FAIL else 0)
