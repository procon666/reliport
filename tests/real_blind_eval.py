def num_eq(a, b):
    na = _value_to_number(a); nb = _value_to_number(b)
    if na and nb:
        if na[1] != nb[1]:
            return False
        return _values_close(a, b)
    return a.replace(" ", "") == b.replace(" ", "")

def subj_ok(desc, subj):
    # 标签级只粗查：主体非空即可（真实场景指标归一才是重点，主体宽容）。
    return bool((subj or "").strip())

