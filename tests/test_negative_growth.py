"""专项回归：负增速('-3%的增速')方向语义 → 归入'跌幅'口径。

背景（真实盲测暴露）：含负号增长的增速数值（'录得-3%的增速''同比-5.5%增速'）
曾被抽成 '增长率 | 3%'：负号在 _NUM_RE 层就被丢弃、且语义上是下跌却留在增长率桶，
无法与 '下滑3%/下降3%'（归'跌幅'）交叉验证归并。

方案（用户确认）：负号前导的增长率类值 → 归入'跌幅'，值保持量值('3%'，跌幅自带
负方向，与 下滑3%→跌幅|3% 呈现一致)。仅翻转解析为'增长率'的值：净利率/毛利率/
市场份额等"比率真实为负"(-3%净利率，语义≠下滑3%)本就不进增长率桶，天然不受影响；
范围连字符('5%-3%')由负号判定排除，不被误判。

覆盖断言：
  1. -3%的增速 → 跌幅|3%（值不带负号，与下滑口径同桶同值）
  2. 同比-5.5%增速 → 跌幅
  3. 整体实现-6.8%的同比增速 → 跌幅
  4. 负增长-3% → 跌幅；回升+2% 仍是增长率（正方向不误翻）
  5. 区间连字符 '5%-3%' 两个正值都不被误翻成跌幅
  6. 净利率-3% 是"真实为负"→ 仍归净利率(非跌幅)
  7. 毛利率-2.5% 同理 → 仍归毛利率
  8. 净利率同比下滑3% 既有跌幅不回归
"""
import sys
sys.path.insert(0, '.')
from research_agent.analyzer import _sentence_claims

PASS = 0
FAIL = 0

def check(name, cond, detail=""):
    global PASS, FAIL
    if cond:
        PASS += 1
    else:
        FAIL += 1
        print(f"[FAIL] {name}  {detail}")

def got(sent):
    return [(c["value"], c["indicator"]) for c in _sentence_claims(sent, "u")]

# ---- 1~4. 负增速 → 跌幅（值不带负号） ----
g = got("该公司录得-3%的增速，营收下滑。")
check("-3%的增速 归跌幅|3%", ("3%", "跌幅") in g, f"got={g}")

g = got("净利润同比录得-3.5%的增速。")
check("同比-3.5%增速 归跌幅|3.5%", ("3.5%", "跌幅") in g, f"got={g}")

g = got("营收同比增速为-5.5%。")
check("同比增速为-5.5% 归跌幅", ("5.5%", "跌幅") in g, f"got={g}")

g = got("整体实现-6.8%的同比增速。")
check("-6.8%的同比增速 归跌幅", ("6.8%", "跌幅") in g, f"got={g}")

g = got("2024年录得负增长-3%，2025年回升至+2%。")
check("负增长-3% 归跌幅、回升+2% 仍增长率",
      ("3%", "跌幅") in g and ("2%", "增长率") in g, f"got={g}")

# ---- 5. 区间连字符不误翻 ----
g = got("5%-3%之间波动。")
check("区间'5%-3%'两个正值都不翻成跌幅",
      ("5%", "增长率") in g and ("3%", "增长率") in g
      and not any(i == "跌幅" for _, i in g), f"got={g}")

# ---- 6~7. 比率"真实为负"不误翻成跌幅 ----
g = got("净利率录得-3%，较上年由正转负。")
check("净利率-3% 是真实为负 → 仍归净利率(非跌幅)",
      ("3%", "净利率") in g and not any(i == "跌幅" for _, i in g), f"got={g}")

g = got("毛利率为-2.5%。")
check("毛利率-2.5% 真实为负 → 仍归毛利率",
      ("2.5%", "毛利率") in g and not any(i == "跌幅" for _, i in g), f"got={g}")

# ---- 8. 既有下滑/下降不回归 ----
g = got("净利率同比下滑3%。")
check("净利率同比下滑3% 仍跌幅", ("3%", "跌幅") in g, f"got={g}")

g = got("营收同比下降3.5%。")
check("同比下降3.5% 仍跌幅", ("3.5%", "跌幅") in g, f"got={g}")

print(f"\n========== 负增速专项回归：{PASS} 通过 / {FAIL} 失败 ==========")
sys.exit(1 if FAIL else 0)
