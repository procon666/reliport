# -*- coding: utf-8 -*-
"""真实检索暴露的"数量/代号误抽"专项回归（生物医药/金融真实句）。

背景（真实检索：21财经/医保局/证券时报/新浪 片段逐字摘录）：
  1. 产品代号数字：'PD-1' 里的 1 被当独立量值 → 多抽 '销售额|1'；
  2. 汇率比价基准：'1美元对人民币6.78' 的 '1美元' 是比例分母 → 多抽 '规模|1美元'；
  3. 数量定语计数：'超50个药品降幅超90%' 的 50、'385个药品' 的 385、
     '存续12360只基金' 的 12360、'370只货币基金' 的 370、集采'262家企业382个产品'
     等"实体个数"被就近误绑成规模/跌幅 → 多抽假主张。

修复（_is_metadata_digit 三类新规则）：
  a. 拉丁字母+'-'+数字 = 产品/型号/化学代号（PD-1/IL-6），数字是代号一部分；
  b. '1美元/1欧元/1日元/1英镑'+对/兑 = 汇率比价基准（'1亿美元'长式不受影响）；
  c. 纯整数+通用量词(个/种/家/只/款/批/项) = 实体个数计数（口径描述）；
     —— 人/患者量词(例/位/名/人)属于"人数"指标域，不在此剔除。
带单位的真实量值(5.26亿美元/38亿元/90%/31.9万亿/13万亿)必须保留。
"""
import sys
sys.path.insert(0, '.')
from research_agent.analyzer import _sentence_claims

PASS = 0
FAIL = 0

def check(name, cond, detail=""):
    global PASS, FAIL
    tag = "PASS" if cond else "FAIL"
    if cond:
        PASS += 1
    else:
        FAIL += 1
    print(f"[{tag}] {name}" + (f"  {detail}" if detail else ""))

def vals(sent):
    return [c["value"] for c in _sentence_claims(sent, "x")]

# ---- 1. 产品代号数字不误抽（PD-1 的 1）----
g = vals("礼来与信达生物的合作产品PD-1信迪利单抗2024年全年销售额达5.26亿美元，约合38亿元人民币。")
check("PD-1代号不抽'1'", "1" not in g and "5.26亿美元" in g and "38亿元" in g, f"got={g}")

# ---- 2. 汇率比价基准不误抽（1美元对…）----
g = vals("当日人民币汇率中间价为1美元对人民币6.7828元。")
check("汇率'1美元'基准不抽", "1美元" not in g and "6.7828元" in g, f"got={g}")
g = vals("人民币对美元汇率中间价为6.7894元，1欧元兑7.2元。")
check("汇率'1欧元'基准不抽", "1欧元" not in g and "7.2元" in g, f"got={g}")

# ---- 3. 数量定语计数不误抽（个/只/家）----
g = vals("拟中选的385个药品中，超50个药品拟中选价格降幅超过90%。")
check("'385个/超50个'不抽", "385" not in g and "50" not in g and "90%" in g, f"got={g}")
g = vals("截至2024年末，全市场存续12360只公募基金，净值规模合计31.9万亿元。")
check("'12360只'不抽", "12360" not in g and "31.9万亿" in g, f"got={g}")
g = vals("货币型基金370只，合计规模达13万亿元，占总规模40.8%。")
check("'370只'不抽", "370" not in g and "13万亿" in g and "40.8%" in g, f"got={g}")
g = vals("第九次集采共有262家企业的382个产品参与投标，205家企业的266个产品获中选资格。")
check("集采'家/个'计数全不抽", not g, f"got={g}")

# ---- 3b. 倍数误抽（P0）：'X倍'归'倍数'桶，不污染出货量/营收 ----
def rows_p0(sent):
    return [(c["value"], c["indicator"], c["subject"]) for c in _sentence_claims(sent, "x")]

g = rows_p0("2026上半年全球储能电池出货量，宁德时代以125GWh位居第一，是排名第二的亿纬锂能(48GWh)的2.6倍。")
check("2.6倍→倍数桶(非出货量)",
      ("125GWh", "出货量", "宁德时代") in g and ("48GWh", "出货量", "亿纬锂能") in g
      and any(v == "2.6" and i == "倍数" for v, i, _ in g)
      and not any(v == "2.6" and i == "出货量" for v, i, _ in g), f"got={g}")
g = rows_p0("该公司营收增长5倍达100亿元。")
check("5倍→倍数桶(非营收)",
      any(v == "5" and i == "倍数" for v, i, _ in g) and ("100亿元", "营收", "该公司") in g,
      f"got={g}")

# ---- 4. 回归护栏：真实量值保留、既有句式不误伤 ----
g = vals("默沙东公布的业绩显示，PD-1当年为其贡献了110亿美元收入，同比增幅达54.6%。")
check("真实收入/增幅保留(非纯整)", "110亿美元" in g and "54.6%" in g, f"got={g}")
g = vals("《愤怒的小鸟》系列历史累计下载量突破10亿次。")
check("手游下载量不受影响", "10亿" in g, f"got={g}")
g = vals("2024年中国游戏产业市场规模已突破3257.8亿元，同比增长7.53%。")
check("行业规模不受影响", "3257.8亿元" in g and "7.53%" in g, f"got={g}")
g = vals("截至2024年，《王者荣耀》全球累计下载量超30亿次，玩家覆盖200多个国家。")
check("覆盖'200多个国家'仍过滤", "200" not in g and "30亿" in g, f"got={g}")

print(f"\n========== 数量/代号误抽专项回归：{PASS} 通过 / {FAIL} 失败 ==========")
sys.exit(1 if FAIL else 0)
