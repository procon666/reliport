"""真实检索暴露·陌生行业短板 回归固化。

来源：对盲测(real_scale_blind)之外的陌生行业（钢铁/乳业/手机/光伏/咖啡等）
做真实 WebFetch/WebSearch 时暴露的**既有短板修复**，逐条固化为独立回归，防止
将来改动引擎时靠隐式覆盖而悄悄回归。这些句子原父版全错，现指标/数值/方向正确。

覆盖（对照各修复提交）：
  1. 乳业营收错绑：'营业总收入'收录并归一'营收'，1157.80亿不再错绑到'净利润'
  2. 手机份额劫持：'市场占有率'收录归'市场份额'，19%不再被'同比增长'劫持
  3. 亿元人残尾：'亿元人民币'只显示'亿元'，不带多余'人'字
  4. 负增速方向：'-3%增速'识别为跌幅（值不带负号，与下滑3%同桶）
  5. 光伏装机短式：'装机'→'装机量'，59.59GW 继承装机量指标
  6. 句内变化端点保留：45.8%→47.5% 两个真实观测点并存（不被±15%当噪声吞并）
"""
import sys
sys.path.insert(0, '.')
from research_agent.analyzer import _sentence_claims

PASS = 0
FAIL = 0

def check(name, cond, detail=""):
    global PASS, FAIL
    if cond:
        PASS += 1
    else:
        FAIL += 1
        print(f"[FAIL] {name}  {detail}")

def pairs(sent):
    return {(c["value"], c["indicator"]) for c in _sentence_claims(sent, "u")}

# ---- 1. 乳业营收错绑 ----
g = pairs("公司实现营业总收入1157.80亿元，净利润84.64亿元。")
check("营业总收入1157.80亿元归营收(非错绑净利润)",
      ("1157.80亿元", "营收") in g and ("84.64亿元", "净利润") in g
      and not any(v == "1157.80亿元" and i == "净利润" for v, i in g),
      f"got={g}")

# ---- 2. 手机份额劫持 ----
g = pairs("三星以19%的市场占有率排名榜首，同比增长5%。")
check("市场占有率19%归市场份额(不被同比增长劫持)",
      ("19%", "市场份额") in g and ("5%", "增长率") in g
      and not any(v == "19%" and i == "增长率" for v, i in g),
      f"got={g}")

# ---- 3. 亿元人残尾 ----
g = pairs("咖啡市场规模预计达1200亿元人民币。")
check("'亿元人民币'值不带残尾'人'",
      ("1200亿元", "规模") in g
      and not any("人" in v and v.endswith("人") for v, _ in g), f"got={g}")

# ---- 4. 负增速方向归跌幅 ----
g = pairs("该公司录得-3%的增速。")
check("-3%增速识别为跌幅(非增长率|带符号)",
      ("3%", "跌幅") in g and not any(i == "增长率" for _, i in g), f"got={g}")

# ---- 5. 光伏装机短式 ----
g = pairs("2026年1-5月全国太阳能发电新增装机59.59GW。")
check("'装机'短式→装机量，59.59GW 挂装机量指标",
      ("59.59GW", "装机量") in g, f"got={g}")

# ---- 6. 句内变化端点保留 ----
# 注：句首"份额"短式收录后（轮2），45.8%/47.5% 归"市场份额"（比旧 fallback 的
# "占比"更精确——"份额"即"市场份额"省略写法），端点仍并存。
g = pairs("份额从45.8%提升至47.5%。")
check("45.8%→47.5% 两个真实观测点并存",
      ("45.8%", "市场份额") in g and ("47.5%", "市场份额") in g, f"got={g}")

# ---- 边界：舍入噪声(38.0/38.2)仍合一，不因端点保留而膨胀 ----
g = pairs("占比从38.0%微调至38.2%。")
check("舍入噪声(38.0/38.2)按close合一为1条",
      len(g) == 1 and ("38.0%", "占比") in g, f"got={g}")

print(f"\n========== 陌生行业短板回归：{PASS} 通过 / {FAIL} 失败 ==========")
sys.exit(1 if FAIL else 0)
