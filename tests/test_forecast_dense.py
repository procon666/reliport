# -*- coding: utf-8 -*-
"""预测/区间/双单位·密集多值句式专项（大摩/IEA/WSTS/SEMI —— 真联网检索固化）。

背景（Tavily 真联网检索车市/半导体预测报告，句子逐字摘录）：市场报告最高频的
"预测+同比+渗透率"、"分别增长X%和Y%达到A辆和B辆"、"产销分别完成A和B"、
"达X亿美元较去年Y增长Z%" 等**多值密集句式**。本专项固化验证其召回与分工。
"""
import sys
sys.path.insert(0, '.')
from research_agent.analyzer import _sentence_claims

PASS = 0
FAIL = 0

def check(name, cond, detail=""):
    global PASS, FAIL
    tag = "PASS" if cond else "FAIL"
    if cond:
        PASS += 1
    else:
        FAIL += 1
    print(f"[{tag}] {name}" + (f"  {detail}" if detail else ""))

def rows(sent):
    return [(c["value"], c["indicator"]) for c in _sentence_claims(sent, "x")]

# ---- 1. 预测+增长+渗透率 三值 ----
g = rows("大摩预计2026年新能源汽车销量同比增长11%，达到1730万辆，渗透率达到59%。")
check("预测三值:11%增长/1730万销量/59%渗透",
      ("11%", "增长率") in g and ("1730万辆", "销量") in g and ("59%", "渗透率") in g, f"got={g}")

# ---- 2. 分别增长+分别达到 四值配对 ----
g = rows("届时纯电动汽车和插电式混合动力汽车的销量预计将分别增长9%和14%，达到1070万辆和660万辆。")
check("分别增长/达到四值:9%/14%/1070/660",
      ("9%", "增长率") in g and ("14%", "增长率") in g
      and ("1070万辆", "销量") in g and ("660万辆", "销量") in g, f"got={g}")

# ---- 3. 全球量+占比 ----
g = rows("2026年全球电动汽车销量预计将攀升至2300万辆，占全球新车总销量的近30%。")
check("2300万辆销量+30%占比", ("2300万辆", "销量") in g and ("30%", "占比") in g, f"got={g}")

# ---- 4. 全国量+其中+预测量 ----
g = rows("2026年全球新能源汽车销量将稳步攀升至2714万辆，其中中国市场占比约70%，预计销量达1900万辆。")
check("2714万辆+70%占比+1900万辆",
      ("2714万辆", "销量") in g and ("70%", "占比") in g and ("1900万辆", "销量") in g, f"got={g}")

# ---- 5. 产销并列 ----
g = rows("2025年，中国汽车产销分别完成3453.1万辆和3440万辆，同比分别增长10.4%和9.4%。")
check("产销四值:3453.1/3440/10.4%/9.4%",
      any("3453.1" in v for v, _ in g) and any("3440" in v for v, _ in g)
      and ("10.4%", "增长率") in g and ("9.4%", "增长率") in g, f"got={g}")

# ---- 6. 本年vs去年+增长 ----
g = rows("SEMI发布报告称，2025年全球半导体制造设备销售额达到1351亿美元，较2024年的1171亿美元增长15%。")
check("对比三值:1351/1171/15%",
      ("1351亿美元", "销售额") in g and any("1171" in v for v, _ in g)
      and ("15%", "增长率") in g, f"got={g}")

# ---- 7. 季度规模+环比+同比 ----
g = rows("2026年第二季度全球半导体市场规模达3680亿美元，环比上涨35%，同比暴涨104%。")
check("季度三值:3680亿/35%/104%",
      ("3680亿美元", "规模") in g and ("35%", "涨幅") in g and ("104%", "涨幅") in g, f"got={g}")
g = rows("全球半导体市场规模在2026年上半年达到7020亿美元，同比增幅102%。")
check("半年:7020亿+102%增幅",
      ("7020亿美元", "规模") in g and ("102%", "增长率") in g, f"got={g}")

print(f"\n========== 预测/密集多值句式专项：{PASS} 通过 / {FAIL} 失败 ==========")
sys.exit(1 if FAIL else 0)
