# -*- coding: utf-8 -*-
"""主题体裁识别（纯确定性，无 LLM 依赖）。

背景：引擎默认链路（planner 规划 → writer 撰写）的提示词面向"行业市场调研"——
planner 要求覆盖"现状/玩家/数据/趋势/风险"侧面，writer 固定"行业调研分析师"角色。
对"手游发展史/中国汽车工业发展史/XX创业历程"这类**史/叙事**主题，套行业模板会
把"发展史"跑成"行业市场分析"（历史只剩一张小表）。

本模块用**信号词**判定主题体裁（史/叙事 vs 行业/市场），供 planner/writer 选择
各自的规划/撰写模板。设计原则：
- 通用：匹配的是"体裁"，不是某个具体主题名——手游发展史/汽车发展史/创业历程
  都命中，AI 编程助手市场/新能源汽车行业不命中；
- 确定性：不调 LLM，正则即可，便于回归固化（自迭代）；
- 保守：宁可漏判（走原行业模板，输出不理想但稳定），不误判（行业主题被写成
  编年叙事）。
"""

import re

# 史/叙事类信号词。命中即认为主题要"时间脉络"而非"行业现状面"。
# 注意不收录单独出现的"发展/现状/市场"（如"新能源汽车发展现状"不是史）。
_NARRATIVE_WORDS = [
    "发展史", "成长史", "创业史", "变迁史", "演进史", "进化史", "演变史",
    "兴衰史", "盛衰史", "发家史", "沉浮录", "风云录",
    "发展历程", "演进历程", "演变历程", "历史", "历程", "演变", "演进",
    "沿革", "编年", "起源", "由来", "大事记", "简史", "史话",
    "兴衰", "盛衰", "沉浮",  # 生命周期词：'诺基亚兴衰'/'柯达百年沉浮'亦指历史脉络
]

_NARRATIVE_RE = re.compile("|".join(_NARRATIVE_WORDS))


def is_narrative_topic(topic: str) -> bool:
    """主题是否为"史/叙事"类（要编年时间脉络，而非行业现状分析）。

    例：
      "手游发展史" / "中国汽车工业发展史" / "华为创业历程"
      "人工智能的演进" / "电子商务起源与演变" → True
      "AI 编程助手市场调研" / "新能源汽车行业分析" → False
    """
    if not topic:
        return False
    return bool(_NARRATIVE_RE.search(topic))
